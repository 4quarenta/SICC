-- Keep updated_at server-controlled.
create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = public as $$
begin new.updated_at = timezone('utc', now()); return new; end;
$$;
drop trigger if exists people_set_updated_at on public.people;
create trigger people_set_updated_at before update on public.people
for each row execute function public.set_updated_at();
drop trigger if exists operator_profiles_set_updated_at on public.operator_profiles;
create trigger operator_profiles_set_updated_at before update on public.operator_profiles
for each row execute function public.set_updated_at();

-- Authorization helpers read server-owned profiles, never user-editable metadata.
create schema if not exists private;
create or replace function private.is_operator()
returns boolean language sql stable security definer set search_path = public, auth as $$
  select exists (select 1 from public.operator_profiles where user_id = (select auth.uid()));
$$;
create or replace function private.is_admin()
returns boolean language sql stable security definer set search_path = public, auth as $$
  select exists (select 1 from public.operator_profiles where user_id = (select auth.uid()) and role = 'admin');
$$;
revoke all on function private.is_operator() from public;
revoke all on function private.is_admin() from public;
grant execute on function private.is_operator() to authenticated;
grant execute on function private.is_admin() to authenticated;

-- Expose tables only to authenticated operators; RLS remains the authority.
grant usage on schema public to authenticated;
grant select, insert, update, delete on all tables in schema public to authenticated;
alter default privileges in schema public revoke all on tables from anon;
alter default privileges in schema public grant select, insert, update, delete on tables to authenticated;

do $$ declare t text; begin
  foreach t in array array['operator_profiles','operator_invites','factions','people','addresses','approaches','seized_objects','person_media','qtc_alerts','qtc_alert_media','audit_logs'] loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;

create policy operator_profiles_select on public.operator_profiles for select to authenticated
  using (user_id = (select auth.uid()) or (select private.is_admin()));
create policy operator_profiles_insert on public.operator_profiles for insert to authenticated
  with check (user_id = (select auth.uid()) and role = 'operator');
create policy operator_profiles_update on public.operator_profiles for update to authenticated
  using (user_id = (select auth.uid()) or (select private.is_admin()))
  with check ((user_id = (select auth.uid()) and role = 'operator') or (select private.is_admin()));

create policy invites_select on public.operator_invites for select to authenticated
  using (created_by = (select auth.uid()) or (select private.is_admin()));
create policy invites_insert on public.operator_invites for insert to authenticated
  with check ((select private.is_operator()) and created_by = (select auth.uid()));

