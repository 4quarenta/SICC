-- SICC target schema for Supabase PostgreSQL.
-- Apply with `supabase db push` (or the SQL editor) only after reviewing it
-- against the destination project. No production data is included here.

create extension if not exists pgcrypto;
create extension if not exists vector with schema extensions;

create table if not exists public.operator_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  war_name text not null check (char_length(trim(war_name)) between 2 and 80),
  rank text not null check (char_length(trim(rank)) between 1 and 80),
  role text not null default 'operator' check (role in ('admin', 'operator')),
  invited_by uuid references public.operator_profiles(user_id) on delete set null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.operator_invites (
  id bigint generated by default as identity primary key,
  code_hash text not null unique,
  created_by uuid not null references public.operator_profiles(user_id) on delete cascade,
  expires_at timestamptz not null,
  used_at timestamptz,
  used_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default timezone('utc', now()),
  constraint invite_expiry_after_creation check (expires_at > created_at)
);

create table if not exists public.factions (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.people (
  id bigint generated by default as identity primary key,
  full_name text not null,
  nickname text,
  cpf text not null unique,
  birth_date date,
  mother_name text,
  city text,
  state text,
  status text not null default 'review' check (status in ('verified', 'review', 'attention')),
  notes text,
  faction_id bigint references public.factions(id) on delete set null,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.addresses (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  label text not null default 'Residencial',
  address text not null,
  city text,
  state text,
  notes text,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.approaches (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  occurred_at timestamptz not null,
  latitude numeric(10, 7) not null,
  longitude numeric(10, 7) not null,
  accuracy_meters integer,
  location_label text,
  notes text,
  operator_id uuid not null references auth.users(id) on delete restrict,
  operator_email text not null,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.seized_objects (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  description text not null,
  quantity integer not null default 1 check (quantity > 0),
  seized_at timestamptz,
  location text,
  notes text,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.person_media (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  kind text not null check (kind in ('face', 'face_front', 'face_profile', 'tattoo')),
  object_key text not null unique,
  original_name text not null,
  content_type text not null check (content_type in ('image/jpeg', 'image/png', 'image/webp')),
  byte_size integer not null check (byte_size > 0 and byte_size <= 5242880),
  sha256 text not null,
  face_embedding extensions.vector(128),
  face_embedding_model text,
  face_embedding_created_at timestamptz,
  description text,
  captured_at timestamptz,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.qtc_alerts (
  id bigint generated by default as identity primary key,
  category_key text not null,
  category_label text not null,
  priority text not null check (priority in ('Baixa', 'Média', 'Alta', 'Extrema')),
  municipality text not null,
